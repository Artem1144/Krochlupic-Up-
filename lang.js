// ===== HELPER FUNCTIONS =====
var currentLang="ru";

function loadLangPref(){
try{var saved=localStorage.getItem(LANG_KEY);if(saved&&LANG[saved]){currentLang=saved;return true;}}catch(e){}
return false;
}
function saveLangPref(){try{localStorage.setItem(LANG_KEY,currentLang);}catch(e){}}

function t(key){
var v=LANG[currentLang]&&LANG[currentLang][key];
if(v===undefined)v=LANG.ru&&LANG.ru[key];
if(v===undefined)return key;
if(arguments.length>1){
for(var i=1;i<arguments.length;i++){
v=v.split("{"+(i-1)+"}").join(arguments[i]);
}
}
v=v.replace(/\\n/g,"\n");
return v;
}
function tt(key){
var s=t(key);
if(arguments.length>1){
for(var i=1;i<arguments.length;i++){
s=s.split("{"+(i-1)+"}").join(arguments[i]);
}
}
return s;
}
function ttMap(key,map){
var s=t(key);
if(map){
for(var k in map){
s=s.split("{"+k+"}").join(map[k]);
}
}
return s;
}
function setLang(code,skipSave){
if(!LANG[code])return;
currentLang=code;
if(!skipSave)saveLangPref();
applyLang();
document.documentElement.lang=code;
}
function applyLang(){
document.querySelectorAll("[data-i18n]").forEach(function(el){
el.innerHTML=t(el.dataset.i18n);
});
document.querySelectorAll("[data-i18n-ph]").forEach(function(el){
el.setAttribute("placeholder",t(el.dataset.i18nPh));
});
document.querySelectorAll(".lang-btn").forEach(function(b){
if(b.dataset.lang===currentLang)b.classList.add("active");
else b.classList.remove("active");
});
try{window.dispatchEvent(new CustomEvent("langchange",{detail:{lang:currentLang}}));}catch(e){}
}
function detectBrowserLang(){
var nav=(navigator.language||navigator.userLanguage||"ru").toLowerCase();
if(nav.indexOf("ru")===0)return "ru";
if(nav.indexOf("en")===0)return "en";
return "ru";
}
function hasLangPref(){try{return !!localStorage.getItem(LANG_KEY);}catch(e){return false;}}
function getLang(){return currentLang;}
